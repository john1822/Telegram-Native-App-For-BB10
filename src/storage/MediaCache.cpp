QString MediaCache::saveAvatar(qint64 peerId, const QByteArray& data) {
    if (data.isEmpty() || peerId == 0) return QString();

    QByteArray finalBytes = strippedPhotoToJpg(data);

    QString filePath = QString("%1/%2.jpg").arg(m_avatarsDir).arg(peerId);
    QFile file(filePath);
    if (file.open(QIODevice::WriteOnly)) {
        file.write(finalBytes);
        file.flush();
        file.close();
        QString absPath = QFileInfo(filePath).absoluteFilePath();
        emit avatarDownloaded(peerId, absPath);
        return absPath;
    }
    return QString();
}

bool MediaCache::hasPhoto(qint64 photoId) const {
    QString filePath = QString("%1/%2.jpg").arg(m_photosDir).arg(photoId);
    QFile file(filePath);
    return file.exists() && file.size() > 0;
}

QString MediaCache::photoPath(qint64 photoId) const {
    if (!hasPhoto(photoId)) {
        return QString();
    }
    return QFileInfo(QString("%1/%2.jpg").arg(m_photosDir).arg(photoId)).absoluteFilePath();
}

QString MediaCache::savePhoto(qint64 photoId, const QByteArray& data) {
    if (data.isEmpty() || photoId == 0) return QString();

    QByteArray finalBytes = strippedPhotoToJpg(data);

    QString filePath = QString("%1/%2.jpg").arg(m_photosDir).arg(photoId);
    QFile file(filePath);
    if (file.open(QIODevice::WriteOnly)) {
        file.write(finalBytes);
        file.flush();
        file.close();
        QString absPath = QFileInfo(filePath).absoluteFilePath();
        emit photoDownloaded(photoId, absPath);
        return absPath;
    }
    return QString();
}

