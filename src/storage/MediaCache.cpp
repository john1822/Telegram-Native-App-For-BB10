MediaCache* MediaCache::s_instance = 0;

MediaCache::MediaCache(QObject* parent)
    : QObject(parent) {
    s_instance = this;
    initDirectories();
}

MediaCache::~MediaCache() {
    if (s_instance == this) {
        s_instance = 0;
    }
}

MediaCache* MediaCache::instance() {
    if (!s_instance) {
        s_instance = new MediaCache();
    }
    return s_instance;
}

void MediaCache::initDirectories() {
    m_baseDir = "data/media";
    m_avatarsDir = m_baseDir + "/avatars";
    m_photosDir = m_baseDir + "/photos";

    QDir dir;
    if (!dir.exists(m_avatarsDir)) {
        dir.mkpath(m_avatarsDir);
    }
    if (!dir.exists(m_photosDir)) {
        dir.mkpath(m_photosDir);
    }
}

bool MediaCache::hasAvatar(qint64 peerId) const {
    QString filePath = QString("%1/%2.jpg").arg(m_avatarsDir).arg(peerId);
    QFile file(filePath);
    return file.exists() && file.size() > 0;
}

QString MediaCache::avatarPath(qint64 peerId) const {
    if (!hasAvatar(peerId)) {
        return QString();
    }
    return QFileInfo(QString("%1/%2.jpg").arg(m_avatarsDir).arg(peerId)).absoluteFilePath();
}

